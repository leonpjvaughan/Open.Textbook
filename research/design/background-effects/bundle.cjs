// Make one self-contained module per variant, the way the site would ship it.
//
// The prototype splits palette.js from each variant so the bytes of each are
// visible, and index.js so one page can offer the whole menu. A shipped
// background would be one file: the palette reader, one variant, and a boot
// hook. This strips the module syntax for exactly these files and writes
// `dist/<variant>.js`, so the request count and the byte count are both real.
//
//   node research/design/background-effects/bundle.cjs
//
// Deliberately not a general bundler: it understands the five files in this
// directory and nothing else.

const fs = require("node:fs");
const path = require("node:path");

const DIR = __dirname;
const OUT = path.join(DIR, "dist");

const VARIANTS = {
  fluid: { file: "fluid.js", call: "mount" },
  "field-gl": { file: "field-gl.js", call: "mount" },
  "field-2d": { file: "field-2d.js", call: "mount" },
  dots: { file: "dots.js", call: "mount" },
  "gradient-static": { file: "gradient.js", call: "mountStatic" },
  "gradient-animated": { file: "gradient.js", call: "mountAnimated" },
  "gradient-transform": { file: "gradient.js", call: "mountTransform" },
};

function strip(source) {
  return source
    .split("\n")
    .filter((line) => !/^import\s.+from\s+"\.\/.+";\s*$/.test(line))
    .filter((line) => !/^export\s*\{[^}]*\};\s*$/.test(line))
    .map((line) => line.replace(/^export\s+(function|const|let|class)\b/, "$1"))
    .join("\n");
}

function bundle(variant) {
  const { file, call } = VARIANTS[variant];
  const palette = strip(fs.readFileSync(path.join(DIR, "palette.js"), "utf8"));
  const module = strip(fs.readFileSync(path.join(DIR, file), "utf8"));
  return [
    `// GENERATED by bundle.cjs from palette.js + ${file}. Do not edit.`,
    palette,
    module,
    `window.__bgBoot = function () {`,
    `  const handle = ${call}(window.__bgOptions || {});`,
    `  window.__bgHandle = handle;`,
    `  window.__bgReady = true;`,
    `  return handle;`,
    `};`,
    "",
  ].join("\n");
}

fs.mkdirSync(OUT, { recursive: true });
for (const variant of Object.keys(VARIANTS)) {
  const body = bundle(variant);
  fs.writeFileSync(path.join(OUT, `${variant}.js`), body);
  const gzip = require("node:zlib").gzipSync(body, { level: 9 }).length;
  console.log(`${variant.padEnd(18)} ${String(body.length).padStart(6)} B raw  ${String(gzip).padStart(5)} B gz`);
}
