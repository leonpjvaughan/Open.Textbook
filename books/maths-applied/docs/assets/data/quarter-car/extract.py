"""The quarter-car transient, as numbers a page can draw.

Run from a checkout of `suspension-kinematics` with `uv run python`. It integrates the
package's own study, computes the same outputs the page talks about at every step, and
writes JSON. `books/maths-applied/docs/assets/data/quarter-car/README.md` records the
command and the digest.
"""
import json
import sys

import numpy as np
import otkd
from otkd.analysis import outputs
from otkd.problem import dynamics
from otkd.problem.compile import Problem

model = otkd.load("examples/quarter-car")
problem = Problem(model)
q0 = problem.q0()
reference = outputs.make_reference(problem)
start = problem._qstart["chassis"] + 2
z0 = float(q0[start])
travel0 = float(problem.world_points(q0)["wc"][2]) - z0

analysis = model.study
duration = 3.0
steps = 601
trajectory = dynamics.integrate(problem, q0, np.zeros(problem.n), duration=duration, steps=steps)

rows = []
for i, q in enumerate(trajectory.q):
    metrics = outputs.compute(problem, q, reference)
    points = problem.world_points(q)
    rows.append(
        {
            "t": round(float(trajectory.t[i]), 5),
            "heave": round((float(q[start]) - z0) * 1000, 4),  # mm, positive = chassis up
            "camber": round(float(metrics.camber), 5),
            "travel": round(
                ((float(points["wc"][2]) - float(q[start])) - travel0) * 1000, 4
            ),
            "toe": round(float(metrics.toe), 5),
            "energy": round(float(trajectory.energy[i]), 6),
        }
    )

energy0 = rows[0]["energy"]
drift = max(abs(row["energy"] - energy0) for row in rows) / abs(energy0)
payload = {
    "meta": {
        "model": "quarter-car",
        "analysis": "dynamics",
        "duration": duration,
        "steps": steps,
        "generator": f"otkd {otkd.__version__}",
        "command": "uv run python extract_qc.py (see README.md)",
        "energy_drift": float(drift),
        "constraint_max": float(np.max(trajectory.constraint)),
    },
    "rows": rows,
}
out = sys.argv[1]
with open(out, "w") as fh:
    fh.write("// Generated by the package's own dynamics solver. Do not edit by hand.\n")
    fh.write("// The command, the version and the digest are in README.md beside this file.\n")
    fh.write("export const meta = " + json.dumps(payload["meta"], indent=1) + ";\n")
    fh.write("export const rows = [\n")
    for row in payload["rows"]:
        fh.write("  " + json.dumps(row) + ",\n")
    fh.write("];\n")
print(json.dumps(payload["meta"], indent=1))
print("heave mm min/max", min(r["heave"] for r in rows), max(r["heave"] for r in rows))
print("camber min/max", min(r["camber"] for r in rows), max(r["camber"] for r in rows))
print("settled", rows[-1])
