"""The quarter-car transient, as numbers a page can draw.

Run from a checkout of `otkd` with `uv run python extract.py trajectory.js`.
The trajectory is not re-integrated here: the package's own `otkd solve --json` writes it, and
this script only asks for it and maps each step to the four numbers the page draws. That is the
point — the package's output is what the book reads, so there is no second reading of the model
to drift out of step with it.

`study.yaml` beside this file is the only thing the book decides: a longer run than the shipped
study, so §1.6 shows the settling rather than stopping at 0.5 s.
"""

from __future__ import annotations

import hashlib
import json
import sys
import tempfile
from pathlib import Path

import open_textbook.otkd as otkd
from open_textbook.otkd.cli import main as otkd_main

MODEL = "examples/quarter-car"
HERE = Path(__file__).resolve().parent
STUDY = HERE / "study.yaml"


def trajectory() -> dict:
    """Ask the package for the run, through the same CLI a reader would use.

    Called in process rather than through a console script, so the only requirement is that
    `otkd` is importable — which it is, because the script runs inside the package's environment.
    """
    with tempfile.TemporaryDirectory() as work:
        out = Path(work) / "trajectory.json"
        code = otkd_main(["solve", MODEL, "--study", str(STUDY), "--json", str(out), "--quiet"])
        if code != 0:
            raise SystemExit(f"otkd solve exited {code}")
        return json.loads(out.read_text())


def sources() -> dict[str, str]:
    """The four config files the run read, by name, with the digest of their bytes.

    Taken from the package's own resolution of the model rather than from the vendored bundle:
    a digest copied out of the bundle could not disagree with the bundle, and then nothing would
    be recorded at all. The library is included because it lives outside the model directory.

    **The study is the one file the book replaces**, so it is recorded from the bytes this run
    passed to `--study` rather than from the package's resolution of the model. Reading it from
    the model records the shipped 0.5 s study as the input to a 3.0 s run — which is what happened
    the first time, and what `tests/test_maths_applied_data.py` then held in place.
    """
    files = otkd.load(MODEL).files
    digests = {
        Path(path).name: hashlib.sha256(Path(path).read_bytes()).hexdigest()
        for path in files.values()
        if path
    }
    digests[STUDY.name] = hashlib.sha256(STUDY.read_bytes()).hexdigest()
    return digests


def main() -> None:
    data = trajectory()
    steps = data["trajectory"]

    origin = steps[0]["points"]["chassis-origin"]
    z0 = origin[2]
    travel0 = steps[0]["points"]["wc"][2] - z0

    rows = [
        {
            "t": step["t"],
            "heave": round((step["points"]["chassis-origin"][2] - z0) * 1000, 4),
            "camber": step["camber"],
            "travel": round((step["points"]["wc"][2] - step["points"]["chassis-origin"][2] - travel0) * 1000, 4),
            "toe": step["toe"],
            "energy": step["energy"],
        }
        for step in steps
    ]

    energy0 = rows[0]["energy"]
    meta = {
        "model": data["meta"]["model"],
        "analysis": "dynamics",
        "duration": data["meta"]["duration"],
        "steps": data["meta"]["steps"],
        "generator": data["meta"]["generator"],
        "command": "uv run otkd solve examples/quarter-car --study study.yaml --json trajectory.json",
        "sources": sources(),
        "energy_drift": max(abs(row["energy"] - energy0) for row in rows) / abs(energy0),
        "constraint_max": max(step["constraint"] for step in steps),
    }

    out = Path(sys.argv[1] if len(sys.argv) > 1 else HERE / "trajectory.js")
    with out.open("w") as fh:
        fh.write("// Generated by the package's own dynamics solver. Do not edit by hand.\n")
        fh.write("// The command, the version and the digest are in README.md beside this file.\n")
        fh.write("export const meta = " + json.dumps(meta, indent=1) + ";\n")
        fh.write("export const rows = [\n")
        for row in rows:
            fh.write("  " + json.dumps(row) + ",\n")
        fh.write("];\n")

    print(json.dumps(meta, indent=1))
    print("heave mm min/max", min(r["heave"] for r in rows), max(r["heave"] for r in rows))
    print("camber min/max", min(r["camber"] for r in rows), max(r["camber"] for r in rows))
    print("settled", rows[-1])


if __name__ == "__main__":
    main()
