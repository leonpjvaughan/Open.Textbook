"""The vendored `otkd` bundle: what is here is what it says it is, and where it came from.

`books/maths-applied/docs/assets/data/otkd/` is another repository's release artefact —
one `out.js` per model and a solver compiled to WebAssembly for each kinematic one. It
is vendored rather than fetched at build time because the collection's rule is that a
clone builds with no network, and because a generated file is drift-checked. The fetch
is `scripts/vendor-otkd.sh`, run by a person when the version changes; CI runs its
`--check`, which needs nothing but the committed bytes.

**Why the hashes matter.** A vendored binary that nobody can check is a binary that
gets edited. The bundle ships a `SHA256SUMS` covering every file and a `MANIFEST.json`
naming the generator and the git commit; the module a browser actually imports carries
the same bytes as base64. These tests are what would notice either drifting.
"""

from __future__ import annotations

import base64
import hashlib
import json
import re
import urllib.error
import urllib.request

import pytest
import yaml

from textbook.book import repo_root

BUNDLE = repo_root() / "books" / "maths-applied" / "docs" / "assets" / "data" / "otkd"
DATA = repo_root() / "books" / "maths-applied" / "docs" / "assets" / "data"
SCRIPT = repo_root() / "scripts" / "vendor-otkd.sh"

#: Models the manifest says carry a kernel; read from the manifest, then asserted here
#: so a model that silently loses its kernel is a failure rather than one fewer loop.
KINEMATIC = (
    "double-wishbone",
    "double-wishbone-compliant",
    "double-wishbone-two-leg",
    "double-wishbone-ubj",
    "ride-height",
)


def manifest() -> dict:
    return json.loads((BUNDLE / "MANIFEST.json").read_text(encoding="utf-8"))


def test_the_bundle_is_the_version_the_vendor_script_pins():
    """One version in one place: the script decides what a refresh fetches.

    A tree fetched at 0.4.0 and a script pinning 0.3.0 would disagree about what the
    next refresh does, and nothing else in the repository would say so.
    """
    pinned = re.search(r'^VERSION="([^"]+)"', SCRIPT.read_text(encoding="utf-8"), re.M)
    assert pinned, "scripts/vendor-otkd.sh does not pin a version"
    assert manifest()["generator"] == f"otkd {pinned.group(1)}", manifest()["generator"]


def test_every_vendored_file_matches_the_bundles_own_sums():
    """`SHA256SUMS` covers every file the release ships.

    The Python distributions are not vendored — they are the package, not this book's
    data — so their lines are skipped by name rather than by ignoring a failure.
    """
    lines = [
        line
        for line in (BUNDLE / "SHA256SUMS").read_text(encoding="utf-8").splitlines()
        if line.strip() and "  package/" not in line
    ]
    assert lines, "the bundle carries no sums"
    for line in lines:
        digest, name = line.split(maxsplit=1)
        path = BUNDLE / name.strip()
        assert path.is_file(), f"{name} is listed but not vendored"
        assert hashlib.sha256(path.read_bytes()).hexdigest() == digest, name


@pytest.mark.parametrize("model", KINEMATIC)
def test_each_kernel_module_embeds_the_binary_it_ships(model):
    """One import and the page has a solver: the binary travels as base64.

    That is deliberate — a `.wasm` fetched over the network is a second file, a MIME
    type and a race. It also means the embedded copy is the one to check, because it is
    the one the browser runs.
    """
    kernel = BUNDLE / "models" / model / "kernel"
    source = (kernel / "kernel.js").read_text(encoding="utf-8")
    match = re.search(r'const BASE64 = "([^"]+)"', source)
    assert match, f"{model}: kernel.js does not embed its binary"
    embedded = base64.b64decode(match.group(1))
    assert hashlib.sha256(embedded).hexdigest() == hashlib.sha256(
        (kernel / "kernel.wasm").read_bytes()
    ).hexdigest(), model


@pytest.mark.parametrize("model", KINEMATIC)
def test_every_payload_is_the_package_output_it_claims_to_be(model):
    """`agreement` may be null: the compliant model has no closed form to compare with.

    That is the same honesty the book asks of its own pages — a missing comparison is
    recorded as missing, not invented.
    """
    text = (BUNDLE / "models" / model / "out.js").read_text(encoding="utf-8")
    assert text.startswith("// Generated by otkd. Do not edit by hand."), model
    for key in ("meta", "sweep", "iterations", "agreement"):
        assert f"export const {key} =" in text, f"{model}: no {key}"
    if "export const agreement = null;" not in text:
        assert '"max_abs_diff"' in text, f"{model}: no agreement figure"


def test_a_dynamics_model_ships_a_kernel_and_no_payload():
    """`quarter-car` is a dynamics study: no sweep to publish, and an integrator to run.

    0.8.0 changed this hole into a kernel — `solver: "dynamics"`, with the trajectory buffers
    beside the pose — so the test now says which of the two is missing and which is there.
    """
    entry = manifest()["models"]["quarter-car"]
    assert entry["payload"].startswith("none")
    assert entry["kernel"] == "kernel.wasm", entry["kernel"]
    model = BUNDLE / "models" / "quarter-car"
    assert not (model / "out.js").exists()
    kernel = json.loads((model / "kernel" / "kernel.json").read_text())
    assert kernel["solver"] == "dynamics"
    assert kernel["integration"]["steps"] >= 2
    assert "traj" in kernel["layout"]["sizes"]
    assert sorted(path.name for path in (model / "source").iterdir()) == sorted(entry["sources"])


def trajectory_meta() -> dict:
    """The run's own record: generator, inputs, duration and the two diagnostics.

    `trajectory.js` writes `meta` with `json.dumps`, so the object is JSON apart from the
    `export const` around it — which is why it can be read here rather than parsed as text.
    """
    text = (DATA / "quarter-car" / "trajectory.js").read_text(encoding="utf-8")
    match = re.search(r"export const meta = (\{.*?\n\});\n", text, re.S)
    assert match, "trajectory.js has no meta object"
    return json.loads(match.group(1))


def test_the_trajectory_records_the_model_the_bundle_ships():
    """§1.6's numbers are a property of one quarter car, and now checkable.

    The trajectory is vendored separately from the bundle, so its `meta.sources` digests
    were a ledger with nothing to check them against. The bundle now carries the four
    config files of every model, dynamics included: a release that changed the coil fails
    here rather than quietly invalidating a chapter.

    **Three of the four, not four.** The study is the file this book overrides, so it is
    checked against the book's own copy by the test below. Asserting the bundle's digest
    for it is what made a 3.0 s run record a 0.5 s study and call the ledger checked.
    """
    recorded = trajectory_meta()["sources"]

    vendored = BUNDLE / "models" / "quarter-car" / "source"
    assert set(recorded) == {path.name for path in vendored.iterdir()}
    for name in ("topology.yaml", "geometry.yaml", "constraints.yaml"):
        assert hashlib.sha256((vendored / name).read_bytes()).hexdigest() == recorded[name], name


def test_the_trajectory_records_the_study_it_ran():
    """The one input the book replaces, recorded from the bytes the run read.

    `extract.py` passes `--study` the book's own file and used to ask the package for the
    digests of the model's, so a 3.0 s run named the shipped 0.5 s study as its input. Two
    checks, because they fail differently: the digest says *which* file the run recorded,
    and the declared duration and step count say whether that file is the one it ran. The
    second is what a reader can verify without hashing anything.
    """
    meta = trajectory_meta()
    study = DATA / "quarter-car" / "study.yaml"
    shipped = BUNDLE / "models" / "quarter-car" / "source" / "study.yaml"
    recorded = meta["sources"]["study.yaml"]
    assert recorded == hashlib.sha256(study.read_bytes()).hexdigest(), (
        "the run records a study other than the 3.0 s file beside it"
    )

    by_digest = {hashlib.sha256(path.read_bytes()).hexdigest(): path for path in (study, shipped)}
    assert recorded in by_digest, "the recorded study is neither the book's nor the release's"
    declared = yaml.safe_load(by_digest[recorded].read_text(encoding="utf-8"))
    assert (meta["duration"], meta["steps"]) == (declared["duration"], declared["steps"]), (
        f"the run took {meta['duration']} s in {meta['steps']} steps and the study it "
        f"records declares {declared['duration']} s in {declared['steps']}"
    )


def test_the_trajectory_is_the_version_the_vendor_script_pins():
    """The run and the bundle have to be the same release, or §1.6 quotes a model we do not ship."""
    assert trajectory_meta()["generator"] == manifest()["generator"]

# --- the page's links and the kernel's sparsity -------------------------------


def book_pages() -> list[Path]:
    """Every Markdown page this book ships, whatever the chapter or depth directory."""
    return sorted((repo_root() / "books" / "maths-applied" / "docs").rglob("*.md"))


def package_links() -> set[str]:
    """Every suspension-kinematics blob URL the book prints."""
    found = set()
    for page in book_pages():
        found.update(
            re.findall(
                r"https://github\.com/leonpjvaughan/suspension-kinematics/blob/[^)\s]+",
                page.read_text(encoding="utf-8"),
            )
        )
    return found


def test_every_package_link_names_a_file_the_package_has():
    """The package renamed `src/suspension/` to `src/otkd/`; a dead link is a dead end.

    The network is not a build dependency, so this test skips when it is unavailable.
    A 404 still fails: the check exists to catch a rename, not to pass when GitHub is
    unreachable.
    """
    links = package_links()
    assert links, "the book has no suspension-kinematics blob links"
    for url in sorted(links):
        match = re.fullmatch(
            r"https://github\.com/leonpjvaughan/suspension-kinematics/blob/[^/]+/(.+)", url
        )
        assert match, f"not a blob URL: {url}"
        api = (
            "https://api.github.com/repos/leonpjvaughan/suspension-kinematics/contents/"
            + match.group(1)
        )
        request = urllib.request.Request(api, headers={"User-Agent": "Open.Textbook"})
        try:
            with urllib.request.urlopen(request, timeout=10) as response:
                assert response.status == 200, f"{url} returned {response.status}"
        except urllib.error.HTTPError as error:
            if error.code in (403, 429):
                pytest.skip(f"GitHub rate-limited the link check: {error}")
            assert error.code != 404, f"{url} is a dead link"
            raise
        except (urllib.error.URLError, TimeoutError) as error:
            pytest.skip(f"network unavailable, so {url} was not checked: {error}")


def test_every_pseudocode_snippet_names_a_file_the_page_links():
    """A snippet's `# file.py` comment and its link are the same file, in the current tree."""
    for page in book_pages():
        text = page.read_text(encoding="utf-8")
        for block in re.findall(r"```python\n(.*?)```", text, re.S):
            first = block.splitlines()[0].strip()
            named = re.fullmatch(r"# ([a-z_]+\.py) — .*", first)
            if not named:
                continue
            name = named.group(1)
            assert re.search(
                rf"\[`{re.escape(name)}`\]\(https://github\.com/leonpjvaughan/"
                rf"suspension-kinematics/blob/[^)]*{re.escape(name)}\)",
                text,
            ), f"{page}: the {name} snippet has no link to {name}"


def test_the_linear_system_page_sparsity_is_the_vendored_kernels():
    """The 441 / 161 claim is the kernel's Jacobian, not a number typed beside it.

    `kernel.rs` writes every cell, including the zeros, so the count of non-zero
    assignments is derived from the generated Rust and the layout's declared size is
    read from `provenance.json`. A re-vendored topology that changes either number
    fails here instead of leaving the page quoting a matrix the book no longer ships.
    """
    kernel = BUNDLE / "models" / "double-wishbone" / "kernel"
    provenance = json.loads((kernel / "provenance.json").read_text(encoding="utf-8"))
    declared = provenance["layout"]["sizes"]["jac"]
    unknowns = provenance["layout"]["sizes"]["q"]

    rust = (kernel / "kernel.rs").read_text(encoding="utf-8")
    body = rust[rust.index("fn compute_inner") : rust.index('pub extern "C" fn compute')]
    assignments = re.findall(r"jac\[\d+\] = ([^;]+);", body)
    non_zero = sum(1 for value in assignments if value.strip() != "0.0")
    assert len(assignments) == declared, f"the Rust writes {len(assignments)} Jacobian cells"

    page = (
        repo_root()
        / "books"
        / "numerical-methods"
        / "docs"
        / "linear-system"
        / "index.md"
    ).read_text(encoding="utf-8")
    match = re.search(
        r"Jacobian has (\d+) entries, of which \*\*(\d+) are not zero\*\*", page
    )
    assert match, "the linear-system page no longer states its Jacobian's sparsity"
    assert (int(match.group(1)), int(match.group(2))) == (declared, non_zero)
    assert re.search(rf"solves\s+{unknowns}\s+equations", page), (
        f"the page no longer names the kernel's {unknowns} unknowns"
    )


def test_the_quarter_car_is_undamped_and_the_pages_say_so():
    """A release that adds a damper changes the class, the period and the prose together.

    §1.6 now calls the run conservative and says it repeats. That is true only while the
    coil is a spring with no damper. The test reads the vendored model, then both pages
    that describe it, so a re-vendor cannot silently turn a conservative oscillator into
    a parabolic decay.
    """
    topology = yaml.safe_load(
        (BUNDLE / "models" / "quarter-car" / "source" / "topology.yaml").read_text(
            encoding="utf-8"
        )
    )
    coil = next(joint for joint in topology["joints"] if joint["name"] == "coil")
    assert coil["modes"] == {"length": "spring"}, "the quarter car now has a damper"

    section = (
        repo_root()
        / "books"
        / "maths-applied"
        / "docs"
        / "Chapter 1"
        / "Section 1.6"
        / "Walkthrough"
        / "index.md"
    ).read_text(encoding="utf-8")
    flat = " ".join(section.split())
    assert "conservative" in flat
    assert "no damper" in flat
    assert "the next model, not this one" in flat
    assert "parabolic" not in flat

    worked = (
        repo_root() / "books" / "numerical-methods" / "docs" / "worked-case" / "index.md"
    ).read_text(encoding="utf-8")
    assert "mass, a spring and a damper" not in worked


